import assert from "node:assert/strict";
import { readFileSync } from "node:fs";

const read = (path) => readFileSync(new URL(`../${path}`, import.meta.url), "utf8");
const upload = read("app/api/orders/[id]/requirement-attachments/route.ts");
const download = read("app/api/attachments/[id]/route.ts");
const form = read("components/pi-order-form.tsx");
const warehouse = read("app/api/stock-orders/[id]/route.ts");
const orderList = read("app/api/orders/route.ts");
const stockList = read("app/api/stock-orders/route.ts");
const attachmentView = read("components/pi-requirement-attachments.tsx");
const printPreview = read("components/order-print-preview.tsx");
const stockExport = read("app/api/stock-orders/[id]/export/route.ts");
const stockExportImages = read("lib/orders/stock-export-requirement-images.ts");
const piExport = read("app/api/orders/[id]/export/route.ts");

assert.match(upload, /order\.status !== "DRAFT"/);
assert.match(upload, /\(order\.prepared_by \|\| order\.sales_user_id\) !== account\.id/);
assert.match(upload, /isPiRequirementImage\(content, file\.type\)/);
assert.match(upload, /PI_REQUIREMENT_IMAGE_COUNT_LIMIT_PER_LINE/);
assert.match(upload, /PI_REQUIREMENT_IMAGE_COUNT_LIMIT_PER_ORDER/);
assert.match(upload, /countResult\.count \|\| 0/);
assert.match(form, /PI_REQUIREMENT_IMAGE_COUNT_LIMIT_PER_LINE/);
assert.match(form, /PI_REQUIREMENT_IMAGE_COUNT_LIMIT_PER_ORDER/);
assert.match(form, /PI_REQUIREMENT_IMAGE_LIMIT/);
assert.match(upload, /不超过 5MB/);
assert.match(form, /不超过 5MB/);
assert.match(form, /整单最多 5 张；每个产品项最多 3 张/);
assert.match(upload, /sales_order_item_id: lineResult\?\.data\?\.id/);
assert.match(upload, /if \(inserted\.error\) \{[\s\S]*remove\(\[storagePath\]\)/);
assert.match(form, /await uploadRequirementFiles\(orderId\);[\s\S]*if \(submitToWarehouse\)/);
assert.match(warehouse, /requirement_attachments: resolvePiRequirementAttachments\(requirementAttachments\.data \|\| \[\], activePiItems\.data \|\| \[\]\)/);
assert.match(download, /account\.role === "WAREHOUSE" && hasPermission\(account, "stock\.view"\)/);
assert.match(download, /stock\.data && stock\.data\.status !== "DRAFT"/);
assert.match(orderList, /hasPermission\(account, "customers\.view"\)[\s\S]*supabase\.from\("customers"\)\.select\("id"\)/);
assert.match(stockList, /hasPermission\(account, "customers\.view"\)[\s\S]*supabase\.from\("customers"\)\.select\("id"\)/);
assert.match(attachmentView, /const src = `\/api\/attachments\/\$\{item\.id\}\?preview=1`[\s\S]*<Image src=\{src\}[^>]*unoptimized loading="eager"/, "理货附件详情应内嵌即时可见缩略图并保持点击查看原图入口");
assert.match(printPreview, /理货要求图片附件（内部备货参考）[\s\S]*PiRequirementAttachments/, "PI 预览打印应展示整单和单项理货图片");
assert.match(printPreview, /PiRequirementAttachments attachments=\{stock\.requirement_attachments \|\| \[\]\} lineNumber=\{null\}/, "备货单打印应展示整单图片附件");
assert.match(printPreview, /lineNumber=\{item\.line_number\} className="mt-1"/, "备货单打印应将附件放在对应产品行");
assert.match(stockExport, /loadStockExportRequirementImages\(admin, \[order\.sales_order_id\], request\.url\)/, "单份备货单导出应使用受保护的图片处理器");
assert.match(stockExportImages, /storage\.from\("crm-attachments"\)\.download\(attachment\.storage_path\)/, "导出缩略图必须从私有存储读取真实原图");
assert.match(stockExportImages, /resize\(68, 44[\s\S]*jpeg\(\{ quality: 70/);
assert.match(stockExportImages, /new URL\(`\/api\/attachments\/\$\{attachment\.id\}\?preview=1`, requestUrl\)/, "缩略图必须链接到受权限保护的预览路由");
assert.match(piExport, /requirementAttachments = resolvePiRequirementAttachments[\s\S]*url: new URL\(`\/api\/attachments\/\$\{item\.id\}\?preview=1`/);
assert.match(piExport, /buildDirectPiWorkbook\([\s\S]*requirementAttachments/);
console.log("PI requirement attachment and customer-link contracts passed");
