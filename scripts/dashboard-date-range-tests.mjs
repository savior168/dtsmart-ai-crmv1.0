import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { resolve } from "node:path";
import { createJiti } from "jiti";

const jiti = createJiti(import.meta.url, { alias: { "@": resolve(".") } });
const { DASHBOARD_BASE_DATE, dashboardBusinessDateKey, dashboardDefaultDateRange, dashboardDatePresetRange } = await jiti.import("../lib/dashboard-date-range.ts");
const { countryFilterRawValues } = await jiti.import("../lib/countries.ts");
const day = new Date("2026-10-10T04:00:00.000Z");
assert.equal(DASHBOARD_BASE_DATE, "2026-08-01");
assert.deepEqual(dashboardDefaultDateRange(day), { from: "2026-08-01", to: "2026-10-10" });
assert.deepEqual(dashboardDatePresetRange("WEEK", day), { from: "2026-10-05", to: "2026-10-10" });
assert.deepEqual(dashboardDatePresetRange("MONTH", day), { from: "2026-10-01", to: "2026-10-10" });
assert.deepEqual(dashboardDatePresetRange("QUARTER", day), { from: "2026-10-01", to: "2026-10-10" }, "季度首月与本月范围相同并非失效");
assert.deepEqual(dashboardDatePresetRange("QUARTER", new Date("2026-09-30T12:00:00.000Z")), { from: "2026-07-01", to: "2026-09-30" });
assert.deepEqual(dashboardDatePresetRange("YEAR", day), { from: "2026-01-01", to: "2026-10-10" });
assert.deepEqual(dashboardDatePresetRange("WEEK", new Date("2026-10-11T04:00:00.000Z")), { from: "2026-10-05", to: "2026-10-11" }, "周日仍应属于当周");
assert.deepEqual(dashboardDatePresetRange("QUARTER", new Date("2026-09-30T16:30:00.000Z")), { from: "2026-10-01", to: "2026-10-01" }, "跨北京时间午夜应进入下一季度");
assert.equal(dashboardBusinessDateKey(new Date("2026-09-30T16:00:00.000Z")), "2026-10-01");
const api = await readFile(new URL("../app/api/dashboard/stats/route.ts", import.meta.url), "utf8");
const ui = await readFile(new URL("../components/crm-dashboard.tsx", import.meta.url), "utf8");
assert.match(api, /new Date\(`\$\{DASHBOARD_BASE_DATE\}T00:00:00\+08:00`\)/, "接口省略日期时须与页面默认口径一致");
assert.match(api, /const exclusiveTo = new Date\(toDate\.getTime\(\) \+ 24 \* 60 \* 60 \* 1000\)/, "接口结束日须包含北京时间整日");
assert.match(ui, /useState\(\(\) => localDate\(new Date\(now\.getFullYear\(\), now\.getMonth\(\), 1\)\)\)/, "工作台默认从本月首日统计");
assert.match(ui, /setFrom\(localDate\(new Date\(now\.getFullYear\(\), now\.getMonth\(\), 1\)\)\)/, "工作台重置须回到本月首日");
assert.match(ui, /<CompactDateRange label="统计日期" from=\{from\} to=\{to\}/, "工作台须提供紧凑且可编辑的起止日期");
const compactDateRange = await readFile(new URL("../components/ui/compact-date-range.tsx", import.meta.url), "utf8");
assert.match(compactDateRange, /aria-label=\{fromLabel\}/, "开始日期须有明确的辅助技术标签");
assert.match(compactDateRange, /aria-label=\{toLabel\}/, "结束日期须有明确的辅助技术标签");
assert.match(ui, /if \(scopeUserId\) params\.set\("user_id", scopeUserId\)/, "未指定归属人时跳转应保持本人范围");
assert.ok(!ui.includes('scopeUserId || "all"'), "默认本人范围不得误传为全部用户");
const customers = await readFile(new URL("../components/customers-view.tsx", import.meta.url), "utf8");
const ownerSelect = await readFile(new URL("../components/user-scope-select.tsx", import.meta.url), "utf8");
assert.match(customers, /requested !== "all" \? requested : fallback/, "主管收到旧的 all 参数时应回退本人");
assert.match(customers, /\["ADMIN", "ORDER_CLERK"\]\.includes\(currentRole\) \? <option value="all">/, "我的客户仅管理员与只读跟单员显示全部用户选项");
assert.match(ownerSelect, /canSelectAll \? <option value="all">/, "共用归属人筛选仅系统管理员显示全部用户选项");
const countryValues = countryFilterRawValues(["IE"]);
assert.ok(countryValues.includes("IE") && countryValues.includes("爱尔兰"), "国家选项须兼容历史中文名与 ISO 代码");
const migration = await readFile(new URL("../supabase/migrations/202610100005_dashboard_customer_filter_alignment.sql", import.meta.url), "utf8");
assert.match(migration, /c\.country = any \(string_to_array\(p_country, chr\(31\)\)\)/, "工作台聚合须按客户列表相同的原始国家值精确匹配");
assert.match(migration, /c\.status <> ''RELEASED''/, "工作台聚合须排除我的客户不显示的历史释放记录");
assert.match(api, /countryFilterRawValues\(\[country\]\)/, "工作台聚合与明细须使用同一国家别名集合");
assert.match(api, /todayFollowupsQuery = todayFollowupsQuery\.in\("country", countryValues\)/, "今日待跟进须遵从国家筛选");
const followups = await readFile(new URL("../components/followups-view.tsx", import.meta.url), "utf8");
assert.match(followups, /searchParams\.getAll\("country"\)/, "跟进明细须回显工作台传入的国家");
console.log("工作台日期范围、北京时间边界及主管客户范围测试通过。");
