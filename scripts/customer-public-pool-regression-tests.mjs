import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";

const read = (path) => readFileSync(resolve(process.cwd(), path), "utf8");
const migration = read("supabase/migrations/202609020001_customer_public_pool_workflow.sql");
const closedLoop = read("supabase/migrations/202609030001_customer_center_closed_loop.sql");
const poolApi = read("app/api/customers/public-pool/route.ts");
const poolView = read("components/customer-public-pool-view.tsx");
const poolDeleteApi = read("app/api/customers/public-pool/delete/route.ts");
const permanentDelete = read("lib/customers/soft-delete.ts");
const userApi = read("app/api/admin/users/route.ts");
const orderApi = read("app/api/orders/route.ts");
const sidebar = read("components/app-shell.tsx");
const managerRules = read("supabase/migrations/202609020003_user_manager_rules.sql");
const lifecycleRules = read("supabase/migrations/202609020004_customer_document_stage_sync.sql");
const manualStatusRules = read("supabase/migrations/202609030002_restore_single_customer_stage_change.sql");

assert.match(migration, /target\.owner_id is not null[\s\S]*已被认领或不属于管理员可分配范围/, "管理员批量分配必须拒绝已有归属客户");
assert.match(migration, /source_user\.status not in \('DISABLED','DEPARTED'\)/, "离职交接仅允许停用或离职账号");
assert.match(migration, /request_owner\.manager_id is distinct from actor\.id/, "主管只能审核直属销售员续期");
assert.match(migration, /next_count<=2 or actor\.role='SUPERVISOR'/, "销售前两次自动续期、主管本人无需审批");
assert.match(migration, /effective_expire-interval '15 days'/, "续期需在到期前15天开放");
assert.match(migration, /effective_expire\+interval '3 days'/, "续期宽限期必须限制为3天");
assert.match(closedLoop, /needs_admin[\s\S]*PENDING_ALLOCATION[\s\S]*AVAILABLE/, "到期客户必须按活动业务和账号状态分流");
assert.match(closedLoop, /release_customer[\s\S]*acquisition_scope='PUBLIC_POOL'[\s\S]*pool_status='AVAILABLE'/, "普通客户主动释放后必须进入公海");
assert.match(closedLoop, /claim_public_customer[\s\S]*status='CLAIMED'[\s\S]*pool_status='CLAIMED'/, "认领只建立潜在客户归属，不得伪造意向阶段");
assert.match(manualStatusRules, /drop trigger if exists attachments_promote_evidenced_interest/, "跟进凭证不得自动修改客户阶段");
assert.match(migration, /lower\(trim\(coalesce\(name,''\)\)\)='eva'/i, "销售员默认上级应优先 Eva");
assert.match(migration, /CUSTOMER_ACCOUNT_HANDOVER/, "离职交接必须写入审计日志");
assert.match(poolApi, /contact_masked: !full/, "已认领公海客户必须对非归属销售员脱敏");
assert.match(poolApi, /own \|\| elevated/, "仅归属人或高级只读角色可打开完整客户详情");
assert.match(userApi, /historyCount > 0/, "存在业务历史的账号不得物理删除");
assert.match(userApi, /action === "CREATE"/, "系统管理员应能新增用户");
assert.match(userApi, /action === "UPDATE_MANAGER"/, "系统管理员应能修改销售直属上级");
assert.match(managerRules, /update public\.users set manager_id=null where role='SUPERVISOR'/, "主管默认必须没有上级");
assert.match(lifecycleRules, /quotes_promote_customer_stage[\s\S]*sales_orders_promote_customer_stage/, "历史迁移应保留可追溯的原始单据阶段规则");
assert.match(manualStatusRules, /drop trigger if exists quotes_promote_customer_stage[\s\S]*drop trigger if exists sales_orders_promote_customer_stage/, "最新迁移必须撤销所有单据自动阶段变更");
assert.match(poolApi, /tab === "available"[\s\S]*eq\("status", "UNCLAIMED"\)[\s\S]*is\("owner_id", null\)/, "待认领公海必须只包含无归属待认领客户");
assert.match(poolApi, /tab === "claimed"[\s\S]*neq\("status", "UNCLAIMED"\)[\s\S]*not\("owner_id", "is", null\)/, "已认领公海记录必须与待认领客户严格隔离");
assert.match(poolView, /available: "待认领客户"[\s\S]*claimed: "认领记录"/, "公海页签必须区分可认领数据与历史认领记录");
assert.doesNotMatch(poolView, /潜在客户（未认领）|潜在客户（已归属）|提交凭证并认领<\/button>/, "客户公海不得出现阶段和归属状态混用的歧义文案");
assert.match(poolView, /border-blue-200 bg-blue-50[\s\S]*认领/, "认领按钮必须采用克制的浅色操作样式");
assert.match(poolDeleteApi, /requireAdmin\(\)[\s\S]*请填写永久删除原因[\s\S]*permanentlyDeleteCustomers/, "公海永久删除必须仅限系统管理员并要求原因");
assert.match(permanentDelete, /quotes[\s\S]*sales_orders[\s\S]*客户已有报价或订单记录/, "存在报价或订单的客户不得物理删除");
assert.match(poolApi, /params\.get\("options"\) === "1"[\s\S]*industries[\s\S]*owners/, "客户公海必须提供完整筛选选项");
assert.doesNotMatch(orderApi, /stock:stock_orders\(/, "销售订单列表不得使用存在双外键歧义的嵌套关系");
assert.match(orderApi, /\.in\("sales_order_id", orderIds\)/, "备货单应按明确 sales_order_id 查询并合并");
assert.match(sidebar, /dtsmart-sidebar-collapsed/, "侧栏收起状态应跨页面持久化");
assert.match(sidebar, /href: "\/customers\/pool"/, "客户中心必须提供客户公海入口");
assert.match(closedLoop, /old\.origin_source[\s\S]*new\.origin_source[\s\S]*客户原始来源由系统保留，不能修改/, "系统获客来源标记必须不可被前端篡改");

console.log("customer public-pool regression tests passed");
