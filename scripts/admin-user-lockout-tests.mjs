import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { canApplyLifecycleAction, canSetTimedLock, canUnlockAccount, effectiveAccountStatus, isTimedLockActive, nextFailedLogin } from "../lib/auth/lockout.ts";

const now = Date.parse("2026-10-19T00:00:00.000Z");
const future = new Date(now + 15 * 60_000).toISOString();
const past = new Date(now - 1).toISOString();

assert.equal(isTimedLockActive(future, now), true);
assert.equal(isTimedLockActive(past, now), false);
assert.equal(effectiveAccountStatus("ACTIVE", future, now), "LOCKED");
assert.equal(effectiveAccountStatus("ACTIVE", past, now), "ACTIVE");
assert.equal(effectiveAccountStatus("DISABLED", future, now), "DISABLED");
assert.equal(effectiveAccountStatus("DEPARTED", future, now), "DEPARTED");
assert.equal(canSetTimedLock("ACTIVE"), true);
assert.equal(canSetTimedLock("LOCKED"), true);
assert.equal(canSetTimedLock("DISABLED"), false);
assert.equal(canSetTimedLock("DEPARTED"), false);
assert.equal(canUnlockAccount("ACTIVE", future, now), true);
assert.equal(canUnlockAccount("ACTIVE", past, now), false);
assert.equal(canUnlockAccount("LOCKED", null, now), true);
assert.equal(canUnlockAccount("DISABLED", future, now), false);
assert.equal(canUnlockAccount("DEPARTED", future, now), false);
assert.equal(canApplyLifecycleAction("PENDING", "APPROVE"), true);
assert.equal(canApplyLifecycleAction("ACTIVE", "APPROVE"), false);
assert.equal(canApplyLifecycleAction("DEPARTED", "ACTIVATE"), false);
assert.equal(canApplyLifecycleAction("LOCKED", "ACTIVATE"), false);
assert.equal(canApplyLifecycleAction("DISABLED", "ACTIVATE"), true);
assert.equal(canApplyLifecycleAction("ACTIVE", "DISABLE"), true);
assert.equal(canApplyLifecycleAction("DEPARTED", "DISABLE"), false);
assert.deepEqual(nextFailedLogin(3, null, 5, 15, now), { attempts: 4, lockedUntil: null });
assert.deepEqual(nextFailedLogin(4, null, 5, 15, now), { attempts: 5, lockedUntil: future });
assert.deepEqual(nextFailedLogin(5, past, 5, 15, now), { attempts: 1, lockedUntil: null });
const batchRoute = await readFile(new URL("../app/api/admin/users/batch/route.ts", import.meta.url), "utf8");
const adminPanel = await readFile(new URL("../components/admin-settings-panels.tsx", import.meta.url), "utf8");
assert.match(batchRoute, /ordered\.some\(\(item\) => item\.role === "SALES"\)/);
assert.match(batchRoute, /manager\.locked_until && Date\.parse\(manager\.locked_until\) > Date\.now\(\)/);
assert.match(batchRoute, /manager_id: managerId \|\| null/);
assert.match(adminPanel, /required=\{managerRequired\}/);
assert.match(adminPanel, /<RowActionMenu ariaLabel=\{\x60\$\{user\.name\|\|user\.email\}的更多操作\x60\} label="更多">/);
assert.match(adminPanel, /<RowActionItem key=\{item\.action\} tone=\{item\.danger\?"danger":"default"\} onClick=\{\(\)=>open\(item\.action\)\}>/);
assert.doesNotMatch(adminPanel, /更多操作\x60\} close=\{\(\)=>setMoreOpen\(false\)\}/, "用户行的更多操作不应再打开整页遮罩弹窗");
console.log("Admin user timed-lock regression tests passed");
