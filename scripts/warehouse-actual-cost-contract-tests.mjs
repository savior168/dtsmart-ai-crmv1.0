import assert from "node:assert/strict";
import { readFileSync } from "node:fs";

const read = (path) => readFileSync(path, "utf8");
const migration = read("supabase/migrations/20261119101255_stock_warehouse_actual_cost.sql");
const shipped = read("supabase/migrations/20261119113000_allow_shipped_pi_price_correction.sql");
const retired = read("supabase/migrations/20261119114000_retire_purchase_price_cost_review.sql");
const shippedMetadata = read("supabase/migrations/20261120014505_allow_verified_cost_metadata_after_shipment.sql");
const noticeResolution = read("supabase/migrations/20261120014941_resolve_actual_cost_notice_after_seller_correction.sql");
const stockRoute = read("app/api/stock-orders/[id]/actual-cost/route.ts");
const stockDetailRoute = read("app/api/stock-orders/[id]/route.ts");
const stockDetailView = read("components/stock-order-detail-view.tsx");
const orderRoute = read("app/api/orders/[id]/route.ts");
const orderView = read("components/order-detail-view.tsx");

assert.match(migration, /warehouse_actual_unit_cost_cny numeric\(14,2\)/);
assert.match(migration, /stock_order_id = stock\.id/);
assert.match(migration, /p_expected_cost_cny is distinct from prior_cost/);
assert.match(migration, /actor\.role not in \('WAREHOUSE', 'ADMIN'\)/);
assert.match(migration, /p_new_cost_cny > seller_cost/);
assert.match(migration, /else\s+update public\.system_notifications set action_status = 'RESOLVED'/);
assert.doesNotMatch(migration, /purchase_unit_price_cny|procurement_cost/);
assert.match(stockRoute, /requirePermission\("stock\.actual_cost\.edit"\)/);
assert.match(stockDetailRoute, /canEditActualCost = \["WAREHOUSE", "ADMIN"\][\s\S]*!\["DRAFT", "CANCELLED"\]\.includes\(order\.status\)/, "所有有效备货阶段均应开放仓库最新成本价核实入口");
assert.match(migration, /stock\.status in \('DRAFT', 'CANCELLED'\)/, "数据库只排除未交仓库的草稿与已取消单");
assert.doesNotMatch(migration, /stock\.status\s*(?:=|<>|not in)\s*'?(?:WAITING|PREPARING|RECEIVED|SORTING|READY_TO_SHIP|SHIPPED|READY|SHORTAGE)/, "有效备货阶段不应限制最新成本价修改");
assert.match(stockDetailView, /item\.can_edit_actual_cost \? <button[\s\S]*setActualCostDraft/, "仓库详情按服务端权限展示修改入口");
assert.match(shipped, /or stock_line\.shipped_quantity>0/);
assert.match(shippedMetadata, /to_jsonb\(new\) - 'estimated_unit_cost_cny'/);
assert.match(shippedMetadata, /to_jsonb\(new\) - 'warehouse_actual_unit_cost_cny'/);
assert.match(shippedMetadata, /old\.shipped_quantity > 0 and to_jsonb\(new\) is distinct from to_jsonb\(old\)/);
assert.match(shippedMetadata, /perform set_config\(''app\.warehouse_actual_cost_apply'', ''1'', true\)/);
assert.match(noticeResolution, /new\.estimated_unit_cost_cny >= stock_line\.warehouse_actual_unit_cost_cny/);
assert.match(noticeResolution, /create trigger resolve_actual_cost_notice_after_seller_correction/);
assert.match(retired, /drop trigger if exists pi_seller_cost_review_after_handoff/);
assert.match(orderRoute, /!\["DRAFT", "CANCELLED"\]\.includes\(order\.data\.status\)/);
assert.match(orderView, /verified != null \? <small[\s\S]*delta > 0 \? "↑ 涨" : "↓ 降"/);
assert.match(orderView, /更正后毛利率：[\s\S]*stockCostByLine\.get\(priceCorrection\.lineNumber\)\?\.warehouse_actual_unit_cost_cny \?\? priceCorrection\.revisedCost/);
assert.doesNotMatch(orderRoute, /supplier_receipt_allocations/);
console.log("Warehouse actual cost and shipped PI correction contracts passed.");
